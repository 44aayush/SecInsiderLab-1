"""Tests for scripts/make_report_tables.py (real outputs; skipped if missing)."""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("make_report_tables", ROOT / "scripts" / "make_report_tables.py")
mrt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mrt)

NEEDED = [
    ROOT.parent / "task2_lab2.pcap_Flow.csv",
    ROOT / "outputs" / "task3" / "cleaning_report.json",
    ROOT / "outputs" / "task4" / "metrics.json",
    ROOT / "outputs" / "realtime" / "predictions.csv",
    ROOT / "outputs" / "realtime" / "run_log.txt",
    ROOT / "artifacts" / "clean.parquet",
    ROOT / "artifacts" / "selected_features_binary.json",
]
EXPECTED = {"t1_flows", "t2_labels", "t3_cleaning", "t3_removed", "t3_split", "t3_scaling",
            "t3_top20", "t4_binary", "t5_realtime"}


def test_escape_and_formats():
    assert mrt.esc("a_b&c") == r"a\_b\&c"
    assert mrt.tt("Init_Win_bytes_backward") == r"\texttt{Init\_Win\_bytes\_backward}"
    assert mrt.fint(223082) == r"223\,082"
    assert mrt.fmet(0.99958328) == "0.9996"
    assert mrt.fpct(0.5484) == r"0.55\,\%"


@pytest.fixture(scope="module")
def tables(tmp_path_factory):
    if any(not p.exists() for p in NEEDED):
        pytest.skip("real output files missing")
    out = tmp_path_factory.mktemp("tables")
    mrt.main(["--out", str(out)])
    return out


def test_files_and_headers(tables):
    assert {f.stem for f in tables.glob("*.tex")} == EXPECTED
    for f in tables.glob("*.tex"):
        t = f.read_text()
        assert t.startswith("% AUTO-GENERATED by scripts/make_report_tables.py")
        assert t.count(r"\toprule") == 1 and t.count(r"\bottomrule") == 1


def test_deterministic(tables, tmp_path):
    mrt.main(["--out", str(tmp_path)])
    for f in tables.glob("*.tex"):
        assert f.read_bytes() == (tmp_path / f.name).read_bytes()


def test_cleaning(tables):
    t = (tables / "t3_cleaning.tex").read_text()
    assert r"223\,082" in t and r"225\,745" in t


def test_t4_binary(tables):
    m = json.loads((ROOT / "outputs" / "task4" / "metrics.json").read_text())
    f1 = f"{m['binary_dt_default']['per_class']['DDoS']['f1']:.4f}"
    assert f1 == "0.9996"
    lines = (tables / "t4_binary.tex").read_text().splitlines()
    dt = [l for l in lines if l.startswith(r"\textbf{DT default}")]
    assert len(dt) == 1 and f1 in dt[0]
    assert len([l for l in lines if r"\textbf{" in l]) == 1


def test_realtime(tables):
    log = (ROOT / "outputs" / "realtime" / "run_log.txt").read_text()
    t = (tables / "t5_realtime.tex").read_text()
    for pat, label in [(r"flows read\s*:\s*(\d+)", "Flows read"),
                       (r"Protocol-0 rows dropped\s*:\s*(\d+)", "Protocol-0 flows dropped"),
                       (r"flows classified\s*:\s*(\d+)", "Flows classified"),
                       (r"DDoS \(alerts\)\s*:\s*(\d+)", "DDoS alerts")]:
        n = re.search(pat, log).group(1)
        assert f"{label} & {n} " in t
    assert "Flows read & 569 " in t and "dropped & 22 " in t
    assert "classified & 547 " in t and "DDoS alerts & 0 " in t


def test_top20_order(tables):
    feats = json.loads((ROOT / "artifacts" / "selected_features_binary.json").read_text())["features"]
    body = (tables / "t3_top20.tex").read_text().split(r"\midrule")[1].split(r"\bottomrule")[0]
    got = [re.search(r"\\texttt\{(.*?)\}", l).group(1).replace(r"\_", "_")
           for l in body.splitlines() if l.strip().endswith(r"\\")]
    assert got == feats


def test_t1_matches_thursday(tables):
    th = ROOT.parent / "Thursday_Dataset" / "reports" / "tables" / "t1_flows.tex"
    if not th.exists():
        pytest.skip("Thursday t1_flows.tex absent")
    assert (tables / "t1_flows.tex").read_bytes() == th.read_bytes()
