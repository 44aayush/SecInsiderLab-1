"""Generate booktabs LaTeX tables for the Friday DDoS report from existing lab outputs.

Reads output files only (never retrains). Output is deterministic (no timestamps).
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import pandas as pd

FRIDAY_ROOT = Path(__file__).resolve().parents[1]
ROOT = FRIDAY_ROOT
LABELS = ["BENIGN", "DDoS"]
REALTIME_MODEL = "binary_dt_default"
GEN = "scripts/make_report_tables.py"
T3 = ROOT / "outputs" / "task3"
T4 = ROOT / "outputs" / "task4"
RT = ROOT / "outputs" / "realtime"
ART = ROOT / "artifacts"
FLOWS_CSV = FRIDAY_ROOT.parent / "task2_lab2.pcap_Flow.csv"

LABEL_FULL = {"BENIGN": "BENIGN", "DDoS": "DDoS"}
LABEL_SHORT = LABEL_FULL
MODEL_NAMES = {
    "lr_default": "LR default",
    "lr_balanced": "LR balanced",
    "dt_default": "DT default",
    "dt_balanced": "DT balanced",
}
STEP_NAMES = {
    "drop_duplicate_header_column": "Drop duplicate header column",
    "replace_inf_with_nan": "Replace $\\pm\\infty$ by NaN",
    "drop_nan_rows": "Drop NaN rows",
    "drop_duplicate_rows": "Drop duplicate rows",
    "drop_constant_columns": "Drop constant columns",
    "drop_identical_columns": "Drop identical columns",
}

_ESC = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


# ---------------------------------------------------------------- helpers
def esc(s: object) -> str:
    """Escape LaTeX special characters (single pass, so no double escaping)."""
    return "".join(_ESC.get(c, c) for c in str(s))


def tt(s: object) -> str:
    return r"\texttt{" + esc(s) + "}"


def fint(n: int | float) -> str:
    return f"{int(round(n)):,}".replace(",", r"\,")


def fmet(x: float) -> str:
    return f"{x:.4f}"


def fpct(x: float) -> str:
    return f"{x:.2f}" + r"\,\%"


def fnum(x: float) -> str:
    """Compact general number for the scaling excerpt."""
    if x < 0:
        return "$-$" + fnum(-x)
    if x == int(x) and abs(x) < 1e15:
        return fint(x)
    if abs(x) >= 1000:
        return fint(x)
    if abs(x) >= 0.01:
        return f"{x:.4f}".rstrip("0").rstrip(".")
    return f"{x:.2e}".replace("e-0", "e-").replace("e+0", "e+")


def fafter(x: float) -> str:
    if abs(x - 1.0) < 1e-9:
        return "1"
    if x == 0:
        return "0"
    return f"{x:.4f}"


def label_full(l: str) -> str:
    return LABEL_FULL.get(l, esc(l))


def tabular(spec: str, header: list[str], rows: list[list[str]], src: str,
            bold_rows: set[int] = frozenset(), midrule_before: set[int] = frozenset(),
            env: str = "tabular") -> str:
    lines = [f"% AUTO-GENERATED by {GEN} from {src} -- do not edit"]
    lines.append(r"\begin{tabularx}{\linewidth}{" + spec + "}" if env == "tabularx"
                 else r"\begin{tabular}{" + spec + "}")
    lines += [r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    for i, r in enumerate(rows):
        if i in midrule_before:
            lines.append(r"\midrule")
        cells = [r"\textbf{" + c + "}" if i in bold_rows and c else c for c in r]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabularx}" if env == "tabularx" else r"\end{tabular}"]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- tables
def t1_flows() -> str:
    df = pd.read_csv(FLOWS_CSV)
    df.columns = df.columns.str.strip()
    proto = df["Protocol"]
    valid = df[proto.isin([6, 17])]
    pk = int((valid["Total Fwd Packet"] + valid["Total Bwd packets"]).sum())
    ports = valid["Dst Port"].value_counts().head(3)
    rows = [
        ["Total flows", fint(len(df))],
        ["TCP flows (6)", fint((proto == 6).sum())],
        ["UDP flows (17)", fint((proto == 17).sum())],
        ["Protocol 0 flows (dropped)", fint((proto == 0).sum())],
        ["Flows classified (TCP + UDP)", fint(len(valid))],
        ["Packets in classified flows", fint(pk)],
    ]
    for rank, (p, c) in enumerate(ports.items(), 1):
        rows.append([f"Top-{rank} destination port", f"{int(p)} ({fint(c)} flows)"])
    return tabular("lr", ["Quantity", "Value"], rows, FLOWS_CSV.name)


def t2_labels() -> str:
    raw = pd.read_csv(T3 / "label_summary_raw.csv").set_index("Label")
    cl = pd.read_csv(T3 / "label_summary_clean.csv").set_index("Label")
    rows = []
    for l in LABELS:
        rows.append([label_full(l), fint(raw.loc[l, "count"]), fpct(raw.loc[l, "percent"]),
                     fint(cl.loc[l, "count"]), fpct(cl.loc[l, "percent"])])
    rows.append(["Total", fint(raw["count"].sum()), fpct(raw["percent"].sum()),
                 fint(cl["count"].sum()), fpct(cl["percent"].sum())])
    return tabular("lrrrr", ["Label", "Raw", "Share", "Cleaned", "Share"], rows,
                   "outputs/task3/label_summary_{raw,clean}.csv",
                   bold_rows={len(rows) - 1}, midrule_before={len(rows) - 1})


def _step_detail(s: dict) -> str:
    k = s["step"]
    neg = "$-$"
    if k == "drop_duplicate_header_column":
        return neg + "1 column (" + tt(s["dropped"][0]) + ")"
    if k == "replace_inf_with_nan":
        inf = ", ".join(f"{tt(c)} {fint(n)}" for c, n in s["inf_per_column"].items())
        nan = ", ".join(f"{tt(c)} {fint(n)}" for c, n in s["nan_per_column"].items())
        return f"inf: {inf}; NaN: {nan}"
    if k in ("drop_nan_rows", "drop_duplicate_rows"):
        by = s["dropped_by_label"]
        if list(by) == ["BENIGN"]:
            who = "all BENIGN"
        else:
            who = ", ".join(f"{fint(n)} {esc(LABEL_SHORT.get(l, l))}" for l, n in by.items())
        return f"{neg}{fint(s['dropped_rows'])} rows ({who})"
    return f"{neg}{fint(len(s['dropped']))} columns"


def t3_cleaning() -> str:
    rep = json.loads((T3 / "cleaning_report.json").read_text())
    rows = []
    for i, s in enumerate(rep["steps"], 1):
        rows.append([str(i), STEP_NAMES.get(s["step"], esc(s["step"])),
                     f"{fint(s['rows_before'])}$\\to${fint(s['rows_after'])}",
                     f"{s['cols_before']}$\\to${s['cols_after']}", _step_detail(s)])
    n_rows, n_feat = rep["final_shape"][0], rep["n_features"]
    rows.append(["", "Result", fint(n_rows), "", f"{fint(n_rows)} rows $\\times$ {n_feat} features"])
    spec = r"rlrrX"
    return tabular(spec, ["\\#", "Step", "Rows", "Cols", "Detail"], rows,
                   "outputs/task3/cleaning_report.json", bold_rows={len(rows) - 1},
                   midrule_before={len(rows) - 1}, env="tabularx")


def t3_removed() -> str:
    rep = json.loads((T3 / "cleaning_report.json").read_text())
    steps = {s["step"]: s for s in rep["steps"]}
    const = steps["drop_constant_columns"]["dropped"]
    rows = [[f"Constant ({len(const)})", ", ".join(tt(c) for c in const)]]
    ident = steps["drop_identical_columns"]
    for kept, drop in ident["pairs"]:
        rows.append(["Identical", f"{tt(kept)} $\\to$ {tt(drop)} (dropped)"])
    return tabular("lX", ["Kind", "Columns"], rows, "outputs/task3/cleaning_report.json",
                   midrule_before={1}, env="tabularx")


def t3_split() -> str:
    df = pd.read_parquet(ART / "clean.parquet", columns=["Label"])
    sp = json.loads((ART / "split_indices.json").read_text())
    tr, te = df["Label"].iloc[sp["train_idx"]], df["Label"].iloc[sp["test_idx"]]
    rows = [[label_full(l), fint((tr == l).sum()), fint((te == l).sum())] for l in LABELS]
    rows.append(["Total", fint(len(tr)), fint(len(te))])
    return tabular("lrr", ["Label", "Train (70\\,\\%)", "Test (30\\,\\%)"], rows,
                   "artifacts/clean.parquet, artifacts/split_indices.json",
                   bold_rows={len(rows) - 1}, midrule_before={len(rows) - 1})


SCALING_FEATS = ["Init_Win_bytes_backward", "Init_Win_bytes_forward", "Destination Port",
                 "Flow Duration", "Bwd IAT Total", "PSH Flag Count"]


def t3_scaling() -> str:
    b = pd.read_csv(T3 / "describe_train_before_scaling.csv", index_col=0)
    a = pd.read_csv(T3 / "describe_train_after_scaling.csv", index_col=0)
    rows = []
    for f in SCALING_FEATS:
        rows.append([tt(f), fnum(b.loc[f, "min"]), fnum(b.loc[f, "max"]), fnum(b.loc[f, "mean"]),
                     fafter(a.loc[f, "min"]), fafter(a.loc[f, "max"]), fafter(a.loc[f, "mean"])])
    hdr = ["Feature", "Min", "Max", "Mean", "Min", "Max", "Mean"]
    head = (r"\toprule" + "\n" + r" & \multicolumn{3}{c}{Before scaling} & \multicolumn{3}{c}{After scaling} \\"
            + "\n" + r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}")
    s = tabular("lrrrrrr", hdr, rows, "outputs/task3/describe_train_{before,after}_scaling.csv")
    return s.replace(r"\toprule", head, 1)


def t3_top20() -> str:
    d = pd.read_csv(T3 / "feature_scores_binary.csv")
    d = d[d["selected"].astype(str) == "True"].sort_values("rank").reset_index(drop=True)
    assert len(d) == 20
    rows = [[str(i + 1), tt(d.feature[i]), f"{d.score[i]:.2f}"] for i in range(20)]
    return tabular("rlr", ["Rank", "Binary feature", "$\\chi^2$"], rows,
                   "outputs/task3/feature_scores_binary.csv")


def t4_binary() -> str:
    comp = pd.read_csv(T4 / "comparison.csv")
    comp = comp[comp["target"] == "binary"].set_index("model")
    metrics = json.loads((T4 / "metrics.json").read_text())
    rows, bold = [], set()
    for i, m in enumerate(MODEL_NAMES):
        r = comp.loc[m]
        (tn, fp), (fn, tp) = metrics[f"binary_{m}"]["confusion_matrix"]
        rows.append([MODEL_NAMES[m], fmet(r.accuracy), fmet(r.macro_f1), fmet(r.ddos_precision),
                     fmet(r.ddos_recall), fmet(r.f1_DDoS), fint(fp), fint(fn),
                     f"{r.fit_s:.2f}", f"{r.infer_ms_per_1k:.3f}"])
        if f"binary_{m}" == REALTIME_MODEL:
            bold.add(i)
    hdr = ["Model", "Acc.", "Macro-F1", "Prec.", "Rec.", "F1", "FP", "FN", "Fit (s)", "Inf. (ms/1k)"]
    return tabular("lrrrrrrrrr", hdr, rows, "outputs/task4/comparison.csv, outputs/task4/metrics.json",
                   bold_rows=bold)


def parse_run_log(text: str) -> dict:
    block = text[text.rindex("Summary"):]
    def g(pat: str) -> re.Match:
        m = re.search(pat, block)
        if not m:
            raise ValueError(f"run_log summary: pattern not found: {pat}")
        return m
    return {
        "read": int(g(r"flows read\s*:\s*(\d+)").group(1)),
        "dropped": int(g(r"Protocol-0 rows dropped\s*:\s*(\d+)").group(1)),
        "replaced": int(g(r"inf/NaN cells replaced\s*:\s*(\d+)").group(1)),
        "classified": int(g(r"flows classified\s*:\s*(\d+)").group(1)),
        "benign": int(g(r"BENIGN\s*:\s*(\d+)").group(1)),
        "attack": int(g(r"DDoS \(alerts\)\s*:\s*(\d+)").group(1)),
        "rate": float(g(r"alert rate\s*:\s*([\d.]+)\s*%").group(1)),
        "lat_mean": float(g(r"mean\s+([\d.]+)").group(1)),
        "lat_median": float(g(r"median\s+([\d.]+)").group(1)),
    }


def t5_realtime() -> str:
    s = parse_run_log((RT / "run_log.txt").read_text())
    pred = pd.read_csv(RT / "predictions.csv")
    n_att = int((pred["pred"] != "BENIGN").sum())
    assert s["classified"] == len(pred), (s["classified"], len(pred))
    assert s["benign"] == len(pred) - n_att, (s["benign"], len(pred) - n_att)
    assert s["attack"] == n_att, (s["attack"], n_att)
    rows = [
        ["Flows read", fint(s["read"])],
        ["Protocol-0 flows dropped", fint(s["dropped"])],
        ["inf/NaN cells replaced", fint(s["replaced"])],
        ["Flows classified", fint(s["classified"])],
        ["Classified BENIGN", fint(s["benign"])],
        ["DDoS alerts", fint(s["attack"])],
        ["Alert rate", fpct(s["rate"])],
        ["Latency per flow, mean (ms)", f"{s['lat_mean']:.3f}"],
        ["Latency per flow, median (ms)", f"{s['lat_median']:.3f}"],
    ]
    return tabular("lr", ["Quantity", "Value"], rows,
                   "outputs/realtime/run_log.txt, outputs/realtime/predictions.csv")


TABLES = {
    "t1_flows": t1_flows, "t2_labels": t2_labels, "t3_cleaning": t3_cleaning,
    "t3_removed": t3_removed, "t3_split": t3_split, "t3_scaling": t3_scaling,
    "t3_top20": t3_top20, "t4_binary": t4_binary,
    "t5_realtime": t5_realtime,
}


def generate(out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, fn in TABLES.items():
        p = out / f"{name}.tex"
        p.write_text(fn(), encoding="utf-8")
        paths.append(p)
    return paths


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=FRIDAY_ROOT / "report" / "tables")
    args = ap.parse_args(argv)
    for p in generate(args.out):
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
