"""Tests for scripts/make_report_tables.py (real outputs; skipped if missing)."""
from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("make_report_tables", ROOT / "scripts" / "make_report_tables.py")
mrt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mrt)

NEEDED = [
    ROOT.parent / "task2_lab2.pcap_Flow.csv",
    ROOT / "outputs" / "task3" / "cleaning_report.json",
    ROOT / "outputs" / "task4" / "metrics.json",
    ROOT / "outputs" / "realtime" / "predictions.csv",
    ROOT / "outputs" / "realtime" / "run_log.txt",
    ROOT / "artifacts" / "clean.parquet",
]


def test_escape_all_specials():
    assert mrt.esc("\\") == r"\textbackslash{}"
    for ch, out in {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}.items():
        assert mrt.esc(ch) == out
    assert mrt.esc("a_b&c") == r"a\_b\&c"
    assert mrt.tt("Init_Win_bytes_backward") == r"\texttt{Init\_Win\_bytes\_backward}"
    assert mrt.tt("Flow Bytes/s") == r"\texttt{Flow Bytes/s}"


def test_number_formats():
    assert mrt.fint(164179) == r"164\,179"
    assert mrt.fint(547) == "547"
    assert mrt.fmet(0.98619631) == "0.9862"
    assert mrt.fpct(0.5484) == r"0.55\,\%"
    assert mrt.fafter(0.9999999999999999) == "1"
    assert mrt.fnum(-1.0) == "$-$1"


@pytest.fixture(scope="module")
def tables(tmp_path_factory):
    if any(not p.exists() for p in NEEDED):
        pytest.skip("real output files missing")
    out = tmp_path_factory.mktemp("tables")
    mrt.main(["--out", str(out)])
    return out


def test_key_cells(tables):
    assert len(list(tables.glob("*.tex"))) == 10
    for f in tables.glob("*.tex"):
        t = f.read_text()
        assert t.startswith("% AUTO-GENERATED by scripts/make_report_tables.py")
        assert t.count(r"\toprule") == 1 and t.count(r"\bottomrule") == 1
    assert "0.9862" in (tables / "t4_binary.tex").read_text()
    assert r"164\,179" in (tables / "t3_cleaning.tex").read_text()
    t5 = (tables / "t5_realtime.tex").read_text()
    assert "22" in t5 and "547" in t5
    top = (tables / "t3_top20.tex").read_text().split(r"\midrule")[1].split(r"\bottomrule")[0]
    assert len([l for l in top.splitlines() if l.strip().endswith(r"\\")]) == 20
    bold = [l for l in (tables / "t4_binary.tex").read_text().splitlines() if r"\textbf{" in l]
    assert len(bold) == 1 and bold[0].startswith(r"\textbf{DT default}")


def test_deterministic(tables, tmp_path):
    mrt.main(["--out", str(tmp_path)])
    for f in tables.glob("*.tex"):
        assert f.read_bytes() == (tmp_path / f.name).read_bytes()
